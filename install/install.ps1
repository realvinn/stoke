# <install>\resources\bin\stoke.cmd, on the per-user PATH. The same edit as
# Settings > Updates > Command line in the app (src/main/stokeCommand.ts).
#
# Read RAW and written back as REG_EXPAND_SZ: the obvious
# [Environment]::GetEnvironmentVariable / SetEnvironmentVariable round trip
# returns the value expanded and writes a plain REG_SZ, which freezes
# %USERPROFILE%\AppData\Local\Microsoft\WindowsApps -- the entry Windows puts
# there itself -- and every other %VAR% entry into a literal, for good. The
# change is then announced by setting and clearing a throwaway variable
# through [Environment], which broadcasts WM_SETTINGCHANGE; a raw registry
# write does not. Never setx, which truncates the value at 1024 characters.
#
# Never fatal: Stoke is installed whether or not this lands.
function Add-StokeToPath([string]$Dir) {
  if (-not (Test-Path -LiteralPath (Join-Path $Dir 'stoke.cmd'))) {
    Write-Row 'command' 'this release has no stoke command yet'
    return
  }
  try {
    $key = [Microsoft.Win32.Registry]::CurrentUser.CreateSubKey('Environment')
    try {
      $raw = [string]$key.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
      $parts = @($raw -split ';' | Where-Object { $_ -ne '' })
      $want = $Dir.TrimEnd('\').ToLowerInvariant()
      $have = @($parts | Where-Object { ([Environment]::ExpandEnvironmentVariables($_)).TrimEnd('\').ToLowerInvariant() -eq $want })
      if ($have.Count -gt 0) {
        Write-Row 'command' 'stoke (its folder is already on your PATH)'
        return
      }
      $key.SetValue('Path', (($parts + $Dir) -join ';'), [Microsoft.Win32.RegistryValueKind]::ExpandString)
    } finally {
      $key.Close()
    }
    [Environment]::SetEnvironmentVariable('STOKE_PATH_CHANGED', '1', 'User')
    [Environment]::SetEnvironmentVariable('STOKE_PATH_CHANGED', $null, 'User')
    Write-Row 'command' 'stoke - on your PATH now; open a new terminal to use it'
  } catch {
    Write-Row 'command' "not added to PATH: $($_.Exception.Message)"
  }
}

# --- digests ---------------------------------------------------------------

# BASE64 of the raw 64-byte digest, which is the form electron-builder writes
# into latest.yml. NOT Get-FileHash, which emits hex: a hex string compared
# against the manifest never matches, and the failure reads exactly like a
# corrupted download.
function Get-Sha512Base64([string]$Path) {
  $sha = [Security.Cryptography.SHA512]::Create()
  try {
    $stream = [IO.File]::OpenRead($Path)
    try {
      return [Convert]::ToBase64String($sha.ComputeHash($stream))
    } finally {
      $stream.Dispose()
    }
  } finally {
    $sha.Dispose()
  }
}

# --- downloading -----------------------------------------------------------

# HttpClient with ResponseHeadersRead, deliberately not Invoke-WebRequest.
#
# Two reasons, and the first one is a hard block rather than a preference. Since
# CVE-2025-54100, Windows PowerShell 5.1's Invoke-WebRequest can raise an
# Internet Explorer first-launch prompt that a piped one-liner has no way to
# answer, unless -UseBasicParsing is passed - and the second reason is that it
# gives no byte-level progress at all, so there would be nothing for the fire to
# burn against.
function Get-StokeDownload([string]$Uri, [string]$OutFile, [int64]$Total, $Plan) {
  try { Add-Type -AssemblyName System.Net.Http -ErrorAction SilentlyContinue } catch { }
  $client = [Net.Http.HttpClient]::new()
  $client.Timeout = [TimeSpan]::FromMinutes(30)
  $opened = $false
  try {
    $resp = $client.GetAsync($Uri, [Net.Http.HttpCompletionOption]::ResponseHeadersRead).GetAwaiter().GetResult()
    if (-not $resp.IsSuccessStatusCode) {
      throw "The download failed: HTTP $([int]$resp.StatusCode) for $Uri. Nothing has been installed."
    }
    $in = $resp.Content.ReadAsStreamAsync().GetAwaiter().GetResult()
    $out = [IO.File]::Create($OutFile)
    $watch = [Diagnostics.Stopwatch]::StartNew()
    $lastDraw = -1
    $script:PlainLast = -1
    if ($Plan.Animate) { Open-Fire; $opened = $true }
    try {
      $buffer = New-Object byte[] 131072
      $done = [int64]0
      while ($true) {
        $read = $in.Read($buffer, 0, $buffer.Length)
        if ($read -le 0) { break }
        $out.Write($buffer, 0, $read)
        $done += $read
        $now = $watch.ElapsedMilliseconds
        if ($now - $lastDraw -ge $FireMs) {
          $lastDraw = $now
          Show-Progress -Done $done -Total $Total -Plan $Plan
        }
      }
      # The last reading belongs to the download being OVER, not to a tick
      # landing on the final byte.
      Show-Progress -Done $done -Total $Total -Plan $Plan -Final
    } finally {
      $out.Dispose()
      $in.Dispose()
    }
  } finally {
    if ($opened) { Reset-Fire }
    $client.Dispose()
  }
}

function Show-Progress([int64]$Done, [int64]$Total, $Plan, [switch]$Final) {
  if ($Plan.Animate) {
    $pct = 0
    if ($Total -gt 0) { $pct = [int][math]::Min(100, ($Done * 100) / $Total) }
    if ($Final) { $pct = 100 }
    Draw-Fire -Percent $pct -Mode $Plan.Color
    return
  }
  # The degraded path: one line per decile, append-only, no carriage return and
  # no escape byte, so a CI log and a support paste show the same thing
  # afterwards. With no total there is no percentage - just the megabytes. A
  # fabricated percent in a log somebody later reads back is worse than none.
  if ($Total -gt 0) {
    $decile = [int][math]::Min(10, [math]::Floor(($Done * 10) / $Total))
  } else {
    $decile = [int][math]::Floor($Done / 10000000)
  }
  if ($decile -le $script:PlainLast) { return }
  $script:PlainLast = $decile
  if ($Total -gt 0) {
    Write-Host ("  {0,5}  {1} MB" -f ("$($decile * 10)%"), (Format-Mb $Done))
  } else {
    Write-Host ("  {0,8} MB" -f (Format-Mb $Done))
  }
}

# --- the fire --------------------------------------------------------------

$script:FireOpen = $false
$script:PlainLast = -1

# Whether this console can render VT sequences at all - by TRYING to turn them
# on and believing SetConsoleMode, never by asking the OS version. A false
# positive prints `<esc>[38;2;255;149;82m` at somebody as the first thing Stoke
# ever does, which is the worst available first impression; and Add-Type failing
# under ConstrainedLanguage or AppLocker is an ordinary corporate way to land in
# exactly that ambiguity.
function Enable-VirtualTerminal {
  if ($PSVersionTable.PSVersion.Major -ge 6) { return $true }
  try {
    if (-not ('StokeVT.Native' -as [type])) {
      Add-Type -Namespace 'StokeVT' -Name 'Native' -MemberDefinition @'
[DllImport("kernel32.dll", SetLastError = true)] public static extern IntPtr GetStdHandle(int nStdHandle);
[DllImport("kernel32.dll", SetLastError = true)] public static extern bool GetConsoleMode(IntPtr hConsoleHandle, out uint lpMode);
[DllImport("kernel32.dll", SetLastError = true)] public static extern bool SetConsoleMode(IntPtr hConsoleHandle, uint dwMode);
'@ -ErrorAction Stop
    }
    $handle = [StokeVT.Native]::GetStdHandle(-11)
    $mode = [uint32]0
    if (-not [StokeVT.Native]::GetConsoleMode($handle, [ref]$mode)) { return $false }
    # ENABLE_VIRTUAL_TERMINAL_PROCESSING
    return [StokeVT.Native]::SetConsoleMode($handle, $mode -bor 0x0004)
  } catch {
    return $false
  }
}

# Whether to animate, and in which colour tier. The rules are the ones in
# src/shared/campfire.ts, plus the Windows-only VT probe above: a console that
# cannot do VT cannot redraw in place either, so that is a degraded reason and
# not merely a colour decision.
function Get-FirePlan {
  $reason = ''
  if ($env:STOKE_NO_ANIMATION) { $reason = 'STOKE_NO_ANIMATION is set' }
  elseif ([Console]::IsOutputRedirected) { $reason = 'stdout is not a terminal' }
  elseif ($env:CI -or $env:GITHUB_ACTIONS -or $env:TF_BUILD) { $reason = 'this is CI' }
  elseif (-not (Enable-VirtualTerminal)) { $reason = 'this console cannot render VT sequences' }

  if (-not $reason) {
    try {
      # Derived from $FireRows rather than hardcoded, for the reason install.sh
      # gives at the same test: the canvas has grown once already.
      $fireMin = $FireRows + 5
      if ([Console]::WindowHeight -lt $fireMin) { $reason = "the window is under $fireMin rows" }
      elseif ([Console]::WindowWidth -lt 20) { $reason = 'the window is under 20 columns' }
    } catch {
      # No console buffer to measure. Unknown is not a reason to degrade.
    }
  }

  if ($reason) {
    # A degraded console gets no colour TIER either, not merely no animation.
    return [pscustomobject]@{ Animate = $false; Color = 'none'; Reason = $reason }
  }

  # NO_COLOR governs colour, not motion: no-color.org says the variable "when
  # present and not an empty string" prevents ANSI colour, and says nothing
  # whatever about animation. The art is a silhouette and reads perfectly in one
  # colour, so the fire still burns.
  $color = 'ansi16'
  if ($env:NO_COLOR) {
    $color = 'none'
  } elseif ($env:WT_SESSION) {
    $color = 'truecolor'
  } elseif ($env:COLORTERM -and ($env:COLORTERM -match '(?i)truecolor|24bit')) {
    $color = 'truecolor'
  }
  # TERM is deliberately not consulted on Windows: the console host rounds
  # anything richer than its own sixteen colours to the nearest of them, and
  # #e85f24, #ff9552 and #ffc48c are close enough that it can collapse all three
  # into one red. The 16-colour tier is a hand-tuned choice here, not a
  # degradation.
  return [pscustomobject]@{ Animate = $true; Color = $color; Reason = '' }
}

# Frame $n as seven rows joined by newlines, coloured, with no cursor movement
# in it. The caller owns the redraw.
function Get-FireFrame([int]$Index, [string]$Mode) {
  if ($Mode -eq 'none') { return ($FireM[$Index] + "`n" + $FireMH) }
  $table = $FireSgr[$Mode]
  $rows = @()
  foreach ($line in (($FireF[$Index] + "`n" + $FireFH) -split "\r?\n")) {
    $out = ''
    $active = ''
    if ($line -ne '') {
      foreach ($seg in ($line -split '\|')) {
        # Segments are KEY:text. Neither delimiter can appear in the art, so
        # the split is unambiguous.
        $key = $seg.Substring(0, 1)
        $text = $seg.Substring(2)
        if ($key -ne '_') {
          $seq = [string]$table[$key]
          # A sequence equal to the one in effect is skipped, and a run of
          # spaces emits none and does not end it. Only the foreground is ever
          # set, so that is safe.
          if ($seq -ne $active) { $out += $Esc + $seq; $active = $seq }
        }
        $out += $text
      }
    }
    # Every painted row ends with a reset: a live foreground across the newline
    # would colour whatever the installer prints next.
    if ($active -ne '') { $out += $Esc + $FireReset }
    $rows += $out
  }
  return ($rows -join "`n")
}

# Hide the cursor and make the canvas exist before drawing into it, so whatever
# scrolling is going to happen has already happened and "up $FireRows" is right
# from the first frame on.
function Open-Fire {
  $script:FireOpen = $true
  $script:FireTick = 0
  [Console]::Out.Write("$Esc[?25l")
  [Console]::Out.Write(("`n" * $FireRows))
}

# Never the alternate screen buffer: leaving it restores the previous one, so
# everything the installer printed - where the app went, what was cleared -
# would be gone the instant it exits, along with the scrollback of anyone
# reading back what an `iex` just did.
function Draw-Fire([int]$Percent, [string]$Mode) {
  $stage = 0
  foreach ($threshold in $FireStagePct) { if ($Percent -ge $threshold) { $stage++ } }
  $flicker = $FireFlicker[$script:FireTick % $FireFlicker.Count]
  $frame = Get-FireFrame -Index (($stage * $FireStride) + $flicker) -Mode $Mode
  # Up $FireRows, then every row prefixed with erase-in-line: three bytes, and
  # correct at any window width where padding to 15 columns would not be.
  $text = "$Esc[$($FireRows)A"
  foreach ($row in ($frame -split "\r?\n")) { $text += "$Esc[K$row`n" }
  # [Console]::Out.Write, never Write-Host: $PSStyle.OutputRendering strips
  # escape sequences out of anything PowerShell formats.
  [Console]::Out.Write($text)
  $script:FireTick++
}

# Cursor FIRST, before anything else that could itself fail, and idempotent
# because the finally blocks above all call it.
function Reset-Fire {
  if (-not $script:FireOpen) { return }
  $script:FireOpen = $false
  try { [Console]::Out.Write("$Esc[?25h$Esc$FireReset") } catch { }
}

$script:FireTick = 0

