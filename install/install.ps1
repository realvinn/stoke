function Install-Stoke {
  # --- where are we ------------------------------------------------------

  # $IsWindows does not exist in Windows PowerShell 5.1, and Set-StrictMode
  # makes reading a missing variable an error, so it cannot simply be tested.
  # -or short-circuits, but the version test has to come first and stand alone.
  $onWindows = $true
  if ($PSVersionTable.PSVersion.Major -ge 6) { $onWindows = $IsWindows }
  if (-not $onWindows) {
    Write-Host ''
    Write-Host '  This is the Windows installer, and this is not Windows.'
    Write-Host '  Run this instead:'
    Write-Host ''
    Write-Host "      $StokeShLine"
    Write-Host ''
    return
  }

  # Inside Stoke's own terminal, the close below (which installing has to do)
  # ends every session Stoke is running -- including the one running this, so
  # the install would stop halfway. Said before anything is downloaded. A dry
  # run closes nothing, so it may carry on.
  if ($env:TERM_PROGRAM -eq 'Stoke' -and -not $env:STOKE_DRY_RUN) {
    Write-Host ''
    Write-Host '  This terminal is inside Stoke, so this installer cannot replace it.'
    Write-Host ''
    Write-Host '  Installing closes Stoke so the new copy can go in, and closing Stoke ends'
    Write-Host '  every session it is running - this one included.'
    Write-Host ''
    Write-Host '  Use Settings > Updates in Stoke instead, or run the same line from a'
    Write-Host '  PowerShell window outside Stoke.'
    Write-Host ''
    return
  }

  $arch = 'x64'
  if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64' -or $env:PROCESSOR_ARCHITEW6432 -eq 'ARM64') {
    $arch = 'arm64'
  }

  $plan = Get-FirePlan
  $tmp = Join-Path ([IO.Path]::GetTempPath()) ("stoke-install-" + [Guid]::NewGuid().ToString('N'))
  New-Item -ItemType Directory -Path $tmp -Force | Out-Null

  try {
    Write-Host ''
    Write-Host '  stoke'
    Write-Host ''

    # --- what is the latest release ---------------------------------------

    # latest.yml is the same feed the installed app's updater reads, so the
    # script and the app agree about what "latest" means by construction. The
    # /releases/latest/download/ redirect needs no API token and has no rate
    # limit worth thinking about.
    $manifestText = Invoke-RestMethod -Uri "$StokeLatestDownload/latest.yml" -UseBasicParsing

    # Assert the body is a manifest before trusting a byte of it. Cloudflare's
    # bot defences answer a challenge with HTML and HTTP 200, which no error
    # handling catches, and GitHub's own error pages are HTML too.
    if ($manifestText -isnot [string] -or $manifestText -notmatch '(?m)^version:\s') {
      throw "What came back for latest.yml is not a release manifest. Something between here and GitHub is answering for it - a proxy, a captive portal or a bot challenge. Nothing has been downloaded."
    }

    $release = Read-StokeManifest -Text $manifestText -Extension '.exe' -Arch $arch
    if (-not $release.Version) { throw 'Could not read a version out of latest.yml.' }
    if (-not $release.File) {
      throw "Stoke $($release.Version) has no Windows $arch build. The release lists no installer for this architecture, so there is nothing to install. See $StokeReleases"
    }
    if ($release.File -notlike 'Stoke-*') {
      throw "The manifest names an unexpected file ($($release.File)). Refusing to download it."
    }

    $installed = Get-InstalledStoke
    Write-Row 'release' $release.Version
    Write-Row 'installed' $(if ($installed.Version) { $installed.Version } else { 'nothing yet' })
    Write-Row 'machine' "windows $arch"
    Write-Row 'file' ("{0} ({1} MB)" -f $release.File, (Format-Mb $release.Size))

    if ($installed.PerMachine) {
      Write-Row 'note' 'the existing Stoke was installed for all users, so Windows will ask for administrator rights'
    }

    if ($installed.Version -and -not $env:STOKE_FORCE) {
      $cmp = Compare-StokeVersion $installed.Version $release.Version
      if ($cmp -eq 0) {
        if (-not $env:STOKE_DRY_RUN) {
          Write-Host ''
          Write-Host "  Stoke $($release.Version) is already installed. Nothing to do."
          Write-Host ''
          return
        }
        Write-Row 'note' 'already current - a real run would stop here; this is a dry run, so it carries on'
      } elseif ($cmp -gt 0) {
        throw "The installed Stoke ($($installed.Version)) is newer than the latest release ($($release.Version)). That is usually a local build, so nothing has been changed. Set `$env:STOKE_FORCE = '1' to replace it anyway."
      }
    }

    # --- download ----------------------------------------------------------

    $exe = Join-Path $tmp $release.File
    Write-Host ''
    Get-StokeDownload -Uri "$StokeLatestDownload/$($release.File)" -OutFile $exe -Total $release.Size -Plan $plan
    Write-Host ''

    $got = (Get-Item $exe).Length
    if ($got -ne $release.Size) {
      Remove-Item $exe -Force -ErrorAction SilentlyContinue
      throw "The download is $got bytes and the release says $($release.Size). The partial file has been deleted and nothing has been installed."
    }

    $digest = Get-Sha512Base64 $exe
    if ($digest -ne $release.Sha512) {
      Remove-Item $exe -Force -ErrorAction SilentlyContinue
      throw "The download does not match the sha512 in the release manifest.`n  expected  $($release.Sha512)`n  got       $digest`nThe file has been deleted and nothing has been installed."
    }
    Write-Row 'verified' 'sha512 matches the release manifest'

    if ($env:STOKE_DRY_RUN) {
      Write-Host ''
      Write-Host "  STOKE_DRY_RUN: stopping here. $($release.File) downloaded and verified;"
      Write-Host '  nothing was installed.'
      Write-Host ''
      return
    }

    # --- install -----------------------------------------------------------

    Stop-StokeGracefully

    # /S and nothing else.
    #
    # No /allusers: with perMachine false the installer's manifest is
    # RequestExecutionLevel user, and /allusers under /S sends it down the
    # elevation path - a UAC prompt out of a one-liner.
    #
    # No /D= on an upgrade either: the installer reads the previous
    # InstallLocation out of the registry and reuses it, so passing a directory
    # can only ever move an install the user had put somewhere deliberately.
    Write-Row 'installing' 'running the installer silently'
    $proc = Start-Process -FilePath $exe -ArgumentList '/S' -Wait -PassThru
    if ($proc.ExitCode -ne 0) {
      throw "The installer exited with code $($proc.ExitCode). Run it by hand to see what it says: $exe"
    }

    # Anything electron-updater has already staged has to go, or the next quit
    # installs THAT over what this script just put down: Stoke sets
    # autoInstallOnAppQuit, so a build downloaded in the update panel and not
    # yet applied is sitting in this directory waiting to win.
    $pending = Join-Path $env:LOCALAPPDATA 'stoke-updater\pending'
    if (Test-Path $pending) {
      Remove-Item $pending -Recurse -Force -ErrorAction SilentlyContinue
      Write-Row 'cleared' "a staged update in $pending"
    }

    $after = Get-InstalledStoke
    if ($after.Location) {
      Write-Row 'installed' $after.Location
      Add-StokeToPath (Join-Path $after.Location 'resources\bin')
    }

    Write-Host ''
    Write-Host "  Stoke $($release.Version) is installed."
    if ($after.Location) {
      $app = Join-Path $after.Location 'Stoke.exe'
      if (Test-Path $app) { Start-Process -FilePath $app }
    }
    Write-Host ''
    Write-Host '  Run the same one-liner again any time to upgrade.'
    Write-Host ''
  } finally {
    # Cursor FIRST, before anything that could itself fail.
    Reset-Fire
    Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
  }
}

