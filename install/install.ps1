# --- the release manifest --------------------------------------------------

# latest.yml, hand-parsed. Its shape is fixed and tiny, and there is no YAML
# parser a bare PowerShell may assume:
#
#     version: 0.9.4
#     files:
#       - url: Stoke-0.9.4-x64-setup.exe
#         sha512: EakW6ulw/k4J7EXuzjTejzbQw2n3PcM+nmJfZm2yEV5dh4h/AYnoYr4WRdzVwB/XKILYG56w4Dn54O6FaeAESA==
#         size: 102576420
#     path: Stoke-0.9.4-x64-setup.exe
#
# sha512 and size are only taken while a url is pending, which is what keeps the
# trailing top-level sha512 out of the answer.
function Read-StokeManifest([string]$Text, [string]$Extension, [string]$Arch) {
  $result = [pscustomobject]@{ Version = ''; File = ''; Sha512 = ''; Size = 0 }
  $url = ''
  $sha = ''
  $size = ''
  foreach ($line in ($Text -split "\r?\n")) {
    if ($line -match '^version:\s*(.+?)\s*$') { $result.Version = $Matches[1] }
    elseif ($line -match '^\s*-\s*url:\s*(.+?)\s*$') { $url = $Matches[1]; $sha = ''; $size = '' }
    elseif ($url -and $line -match '^\s*sha512:\s*(.+?)\s*$') { $sha = $Matches[1] }
    elseif ($url -and $line -match '^\s*size:\s*(\d+)\s*$') { $size = $Matches[1] }
    if ($url -and $sha -and $size) {
      if (-not $result.File -and (Test-StokeAsset -Name $url -Extension $Extension -Arch $Arch)) {
        $result.File = $url
        $result.Sha512 = $sha
        $result.Size = [int64]$size
      }
      $url = ''; $sha = ''; $size = ''
    }
  }
  return $result
}

# Windows names both architectures explicitly, because electron-builder.yml pins
# win's artifactName to ${productName}-${version}-${arch}-setup.${ext}.
function Test-StokeAsset([string]$Name, [string]$Extension, [string]$Arch) {
  if (-not $Name.EndsWith($Extension)) { return $false }
  if ($Arch -eq 'arm64') { return ($Name -match 'arm64') }
  if ($Name -match 'arm64') { return $false }
  return ($Name -match 'x64|x86_64|amd64')
}

# The numeric part only. A -beta.3 suffix is ignored: comparing prerelease
# identifiers properly is a rabbit hole, and all this has to get right is
# same/older/newer on the release line.
function Compare-StokeVersion([string]$A, [string]$B) {
  $pa = ($A -split '-')[0] -split '\.'
  $pb = ($B -split '-')[0] -split '\.'
  for ($i = 0; $i -lt 3; $i++) {
    $x = 0; $y = 0
    if ($i -lt $pa.Count) { [void][int]::TryParse($pa[$i], [ref]$x) }
    if ($i -lt $pb.Count) { [void][int]::TryParse($pb[$i], [ref]$y) }
    if ($x -lt $y) { return -1 }
    if ($x -gt $y) { return 1 }
  }
  return 0
}

# --- what is already here --------------------------------------------------

# Both scopes, and which one matters. HKCU is the ordinary case (perMachine is
# false). HKLM means somebody installed it for all users, and re-running the
# installer there needs elevation - so it is reported before the download rather
# than discovered as a UAC prompt out of a one-liner.
function Get-InstalledStoke {
  $out = [pscustomobject]@{ Version = ''; Location = ''; PerMachine = $false }
  foreach ($root in @('HKCU:', 'HKLM:')) {
    $uninstall = "$root\Software\Microsoft\Windows\CurrentVersion\Uninstall\$AppGuid"
    $install = "$root\Software\$AppGuid"
    try {
      if (Test-Path $uninstall) {
        $key = Get-ItemProperty -Path $uninstall -ErrorAction Stop
        if ($key.PSObject.Properties.Name -contains 'DisplayVersion' -and -not $out.Version) {
          $out.Version = [string]$key.DisplayVersion
          $out.PerMachine = ($root -eq 'HKLM:')
        }
      }
      if (Test-Path $install) {
        $key = Get-ItemProperty -Path $install -ErrorAction Stop
        if ($key.PSObject.Properties.Name -contains 'InstallLocation' -and -not $out.Location) {
          $out.Location = [string]$key.InstallLocation
        }
      }
    } catch {
      # An unreadable key is "we do not know", never "it is not installed".
    }
  }
  return $out
}

# Ask Stoke to close, and wait.
#
# NEVER kill it, and do not let the installer do the killing either. Stoke's
# PTYs die with it but the `claude` processes underneath do not, and the
# restarted app cannot reattach to the orphans. NSIS's own "please close it"
# prompt takes the default under /S and force-stops everything under $INSTDIR,
# which is exactly that failure - so close it first and leave NSIS nothing to do.
function Stop-StokeGracefully {
  $procs = @(Get-Process -Name 'Stoke' -ErrorAction SilentlyContinue)
  if ($procs.Count -eq 0) { return }
  Write-Row 'running' 'asking Stoke to close so it can end its sessions and save your tabs'
  foreach ($p in $procs) {
    try { [void]$p.CloseMainWindow() } catch { }
  }
  for ($i = 0; $i -lt 60; $i++) {
    Start-Sleep -Milliseconds 500
    if (@(Get-Process -Name 'Stoke' -ErrorAction SilentlyContinue).Count -eq 0) { return }
  }
  throw 'Stoke is still running after 30 seconds and would not close. Close it yourself and run this again - killing it would strand the claude processes its sessions are running.'
}

