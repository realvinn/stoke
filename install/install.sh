# How many flicker frames each stage has, so `n = stage * FIRE_STRIDE + flicker`
# addresses the right one of the twelve. The art block states the formula in its
# preamble but carries no variable for the stride, so this is the one number in
# the fire that is hand-written — and `verify:install` asserts it against
# campfire.ts's own stage shape, because a wrong stride is not a crash, it is a
# fire that flickers between the wrong two stages and looks almost right.
FIRE_STRIDE=3

ESC=$(printf '\033')
NL='
'

# The flicker order, as indexable variables. A POSIX shell has no arrays, and
# `set --` would clobber the positional parameters the caller is standing on.
FIRE_FLICK_N=0
for fire_v in $FIRE_FLICKER; do
  eval "FIRE_FLICK_$FIRE_FLICK_N=$fire_v"
  FIRE_FLICK_N=$((FIRE_FLICK_N + 1))
done

# --- talking -------------------------------------------------------------

say() { printf '%s\n' "$*"; }
blank() { printf '\n'; }

# A two-column line, so the transcript of an install reads as a table.
note() { printf '  %-11s %s\n' "$1" "$2"; }

die() {
  fire_cleanup
  blank >&2
  printf '  %s\n' "$@" >&2
  blank >&2
  exit 1
}

