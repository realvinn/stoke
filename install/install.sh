#!/bin/sh
# Stoke, in one line:
#
#     curl -fsSL https://stoke.vinn.dev | sh
#
# Installs or upgrades Stoke on macOS and Linux. Windows is install.ps1; this
# script detects a Windows shell and says so rather than half-working.
#
# It downloads only from github.com/realvinn/stoke/releases and verifies every
# byte against the sha512 in that release's own update manifest before anything
# is installed. STOKE_DRY_RUN=1 does all of that and stops before touching a
# single file outside its temp directory, which is how it is tested.
#
# ---------------------------------------------------------------------------
# Everything is inside main(), which is called on the LAST line, and that is
# structural rather than tidy. `sh` reads its stdin incrementally and executes
# as it reads, so a connection that drops at 60% of a piped script executes the
# first 60% — half an installer is worse than none. A truncated download of this
# file either dies on an unterminated compound command or simply never reaches
# `main "$@"`. Neither one partially installs.
#
# The campfire art block below sits outside main() because it is generated
# verbatim from src/shared/campfire.ts and may not be reindented. It is inert:
# shell variable assignments, nothing executed, nothing reached until main runs.
#
# Debugging flags, all offline and all safe to run:
#     sh install.sh --help
#     sh install.sh --print-plan [tty|pipe]   what the fire would do here
#     sh install.sh --fire-frames <tier>      the twelve frames, painted
#     sh install.sh --sha512 <file>           the manifest's own digest form
# ---------------------------------------------------------------------------
set -eu

# zsh does not split an unquoted parameter expansion on IFS unless it is asked
# to, and three things here depend on that splitting: the flicker table built
# below, the stage thresholds in `fire_stage_of`, and the painter's KEY:text
# segments. Without this line `for fire_v in $FIRE_FLICKER` saw ONE word, so
# `eval "FIRE_FLICK_0=0 1 2 1 0 2"` ran `1` as a command and the script died on
# `command not found: 1` before it had done anything at all — under the shell
# macOS makes the default, which is exactly where somebody types
# `zsh install.sh` after reading it. `zsh -n` parses the file perfectly, which
# is why a suite that only parsed could not see it; verify:install RUNS every
# offline flag under all four shells now.
#
# `setopt sh_word_split` and nothing wider: `emulate sh` would also reset the
# shell options to sh's defaults and take the `set -eu` above with it.
if [ -n "${ZSH_VERSION:-}" ]; then setopt sh_word_split 2>/dev/null || true; fi

STOKE_RELEASES='https://github.com/realvinn/stoke/releases'
STOKE_LATEST_DL="$STOKE_RELEASES/latest/download"
STOKE_PS1_LINE='irm https://stoke.vinn.dev | iex'

# BEGIN CAMPFIRE ART
# Generated by `node scripts/gen-installer-art.mts sh` from src/shared/campfire.ts.
# DO NOT EDIT BY HAND: verify:campfire asserts this block byte for byte against
# the generator, and a hand-encoded row has already shipped a visible `||` once.
#
# Canvas is a fixed 7 rows x 15 columns for every frame, because redraw in
# place is ESC[7A and nothing else -- a shorter frame walks the cursor up the
# screen a row per tick. Flame rows are stored right-trimmed; emit ESC[K per row
# rather than padding to the full width.
#
# 12 frames: 4 stages (spark kindling burning roaring) x 3 flicker frames.
# Pick with: stage from FIRE_STAGE_PCT against the percentage downloaded,
# flicker from FIRE_FLICKER[tick % 6], then n = stage * 3 + flicker and
#   eval "rows=\$FIRE_F$n"    (or FIRE_M$n for the monochrome tier).
#
# Rows are segment-encoded as KEY:text|KEY:text, joined by newlines. Keys:
#   _ uncoloured (spaces)   C core (white-hot)   S spark   M mid   B base   L log
# Neither | nor : can appear in the art, so the split is unambiguous.
# FIRE_M* is the same art with no colour at all, for the monochrome tier.
#
