FIRE_F11='_:   |S:^|_:  |S:.|_:  |C:*|_:  |S:.
_:    |S:)|_: |S:(|_: |S:\|_: |S:/
_:   |M:(|_: |M:)(|C:#|M:)(|_: |M:)
_:  |M:(|_: |M:((|C:###|M:))|_: |M:)
_: |B:(_((|C:#####|B:))_)'
FIRE_FH='L:\__/\_/_\_/\__/
L:.-.,_______,.-.'
FIRE_M0='


