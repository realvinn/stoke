_:    |S:\|_: |S:)|_: |S:(|_: |S:/
_:   |M:(|_: |M:)(|C:#|M:)(|_: |M:)
_:  |M:(|_: |M:((|C:###|M:))|_: |M:)
_: |B:(_((|C:#####|B:))_)'
FIRE_F10='_:  |C:*|_:   |S:.|_:    |S:^
_:   |S:(|_: |S:\|_: |S:)|_: |S:(/)
_:  |M:(|_: |M:)(|_: |C:#|_: |M:)(|_: |M:)
_:  |M:(|_: |M:((|C:###|M:))|_: |M:)
