export interface SessionSettingsInput {
  /**
   * The statusLine KEY this session's three files are named after — not
   * necessarily a session id. It is the session id for everything Stoke mints
   * an id for, and a launch key for a `--continue`, whose id the CLI chooses
   * after launch. See pty.ts, which is the only caller.
   */
  sessionId: string
  ultracode: boolean
  hideStatusLine: boolean
  /** The user's own statusLine command, or '' when there is nothing to echo. */
  passthroughCommand: string
}

/**
 * Everything Stoke puts in one session's `--settings` file.
 *
 * One file, because a second `--settings` silently discards the first —
 * measured against 2.1.221, and the reason this function exists at all rather
 * than each feature appending its own flag.
 *
 * Every session with a key gets the statusLine entry, including a `--continue`
 * — pty.ts gives that one a launch key precisely so it does. Without it, the
 * setting "Hide Claude's status line in Stoke" would silently not apply to the
 * one launch path whose id we do not know in advance.
 *
 * No key at all still means no statusLine entry: there would be nothing to
 * name the payload, the pass-through file or the settings file after.
 */
export function sessionSettingsJson(input: SessionSettingsInput): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  if (input.ultracode) out.ultracode = true
  if (input.sessionId) {
    out.statusLine = { type: 'command', command: statusLineCommand(input.sessionId) }
    /*
     * The hooks that tell Stoke where a session is. Measured against 2.1.237:
     * hooks in a `--settings` file fire, and they MERGE with the user's own
     * (a project-level UserPromptSubmit hook and this one both ran on the
     * same prompt), so this adds to whatever the user has rather than
     * replacing it. Every entry has no matcher, so it applies to every
     * event of that name, and the command prints nothing — a Stop hook that
     * prints is shown in the TUI, and a UserPromptSubmit hook's stdout goes
     * into the model's context. `timeout` is seconds; the wrapper takes
     * milliseconds, so 10 is a ceiling nothing should reach.
     */
    const hook = [{ hooks: [{ type: 'command', command: hookCommand(input.sessionId), timeout: 10 }] }]
    out.hooks = { Stop: hook, Notification: hook, UserPromptSubmit: hook }
  }
  return out
}

/**
 * Write that file and the pass-through command beside it, and return the path
 * for `--settings`. Null means there is nothing to pass.
 *
 * A failure returns null rather than throwing: buildArgs falls back to the
 * ultracode-only file, which does throw if it cannot be written, so the one
 * case that must stay loud — a session that promised ultracode and did not
 * get it — still is.
 */
export function writeSessionSettingsFile(input: SessionSettingsInput): string | null {
  const json = sessionSettingsJson(input)
  if (!Object.keys(json).length) return null
  try {
    mkdirSync(statusLineDir(), { recursive: true })
    if (json.statusLine) writeStatusLineWrapper()
    if (input.sessionId) {
      const cmdFile = passthroughFile(input.sessionId)
      const passthrough = input.hideStatusLine ? '' : input.passthroughCommand.trim()
      // Removed rather than left in place when suppression is on: a stale
      // file would keep printing a line the user has just turned off.
      //
      // The write is atomic (temp + rename), not a plain writeFileSync: the
      // wrapper polls this exact file roughly every 300ms (see WRAPPER_JS
      // above), so an in-place O_TRUNC rewrite is a window where a read lands
      // on an empty or truncated command — and a truncation that still
      // happens to parse as shell would run something other than what the
      // user configured, not just nothing.
      if (passthrough) writeAtomic(cmdFile, passthrough)
      else rmSync(cmdFile, { force: true })
    }
    const file = settingsFileFor(input.sessionId)
    writeAtomic(file, `${JSON.stringify(json, null, 2)}\n`)
    return file
  } catch (err) {
    console.error('[stoke] could not write the session settings file', err)
    return null
  }
}

/** Remove everything written for one session. Called when its PTY exits. */
export function clearSessionFiles(sessionId: string): void {
  if (!sessionId) return
  for (const f of [
    statusLinePayloadFile(sessionId),
    passthroughFile(sessionId),
    settingsFileFor(sessionId),
    sessionEventsFile(sessionId)
  ]) {
    try {
      rmSync(f, { force: true })
    } catch {
      /* a temp sweeper got there first */
    }
  }
}

/**
 * How stale a per-session file must be before the boot sweep below will
 * remove it.
 *
 * Six hours: comfortably longer than any coding session Stoke is likely to
 * hold open in one sitting, and nowhere near the sub-second cadence the
 * wrapper renders on (WRAPPER_JS is re-run roughly three times a second by
 * the CLI), so it cannot mistake a live session's own render gap for death.
 * The failure mode on either side is asymmetric: too low risks deleting a
 * slow-but-live session's files (rare, and only on the '.settings.json'/
 * '.cmd' side — see the "protected keys" comment below for why that is
 * actually contained); too high just means a dead session's few-KB files sit
 * around longer, which is the entire status quo this sweep is fixing, only
 * bounded now instead of unbounded.
 */
const STALE_AFTER_MS = 6 * 60 * 60 * 1000

/** Shared infrastructure the sweep must never remove: `writeStatusLineWrapper` rewrites both unconditionally on every launch anyway, so deleting them only costs the next session a redundant write. */
const NEVER_SWEEP = new Set(['wrapper.mjs', 'run.sh', 'run.cmd'])

/**
 * Split one directory entry into the key its session files share and which
 * of the three kinds this particular file is. `.settings.json` is checked
 * before the plainer `.json` suffix on purpose - the shorter suffix would
 * otherwise match first and leave `.settings` glued onto the key.
 */
function fileKeyAndKind(name: string): { fileKey: string; kind: 'payload' | 'settings' | 'cmd' | 'events' | 'other' } {
  if (name.endsWith('.settings.json')) {
    return { fileKey: name.slice(0, -'.settings.json'.length), kind: 'settings' }
  }
  if (name.endsWith('.events.jsonl')) {
    return { fileKey: name.slice(0, -'.events.jsonl'.length), kind: 'events' }
  }
  if (name.endsWith('.json')) return { fileKey: name.slice(0, -'.json'.length), kind: 'payload' }
  if (name.endsWith('.cmd')) return { fileKey: name.slice(0, -'.cmd'.length), kind: 'cmd' }
  return { fileKey: name, kind: 'other' }
}

/**
 * Remove per-session statusLine files that nothing else will ever clean up:
 * a crash, a SIGKILL, or a launch that failed before its exit handler could
 * be registered all skip `clearSessionFiles` entirely, and it has no other
 * caller anywhere in the app besides pty.ts and the verify suite - so
 * without this, three ordinary ways to end a session (see pty.ts's callers)
 * leave a `.settings.json`/`.cmd`/`.json` triple behind forever. Each
 * `.json` holds that session's token counts and plan-usage percentages, so
 * this is not just tidiness.
 *
 * Meant to run once, at boot, before any session is started.
 *
 * `statusLineDir()` is one directory shared by every Stoke install on the
 * machine - an unpackaged dev run gets its own userData so it never fights
 * an installed copy for the single-instance lock, but both write into the
 * SAME tmpdir. A blanket wipe here would delete the live session files of
 * an already-running installed Stoke the moment a dev build boots, breaking
 * its status line mid-session. So this only ever removes a file whose own
 * mtime is older than `STALE_AFTER_MS` - old enough that no plausible live
 * session, from either install, could have produced it.
 *
 * That age test is sound for a `.json` payload on its own: the wrapper
 * rewrites it on every render (WRAPPER_JS above), so a live session's
 * payload mtime never falls behind by more than a render gap. It is NOT
 * sound on its own for `.settings.json` or `.cmd` - both are written once at
 * launch and never touched again, so their mtime is the session's *start*
 * time. Applying the threshold to them unmodified would eventually reap a
 * long-running session's own settings out from under it. So a
 * `.settings.json`/`.cmd` is protected whenever its sibling `<key>.json`
 * payload is itself fresh - which is exactly the signal that the session
 * that owns that key is still alive and still rendering.
 *
 * Never throws: every filesystem call is individually guarded, matching
 * `writeStatusLineWrapper`'s contract, because a sweep that took the app's
 * boot down with it would be strictly worse than the leak it exists to fix.
 */
export function sweepStaleSessionFiles(now: number = Date.now()): void {
  const dir = statusLineDir()
  let names: string[]
  try {
    names = readdirSync(dir)
  } catch {
    return // nothing written yet on this machine - nothing to sweep
  }

  // Pass 1: which keys have a fresh payload right now. Read before anything
  // is removed, so pass 2's protection check never races its own deletions.
  const freshPayloadKeys = new Set<string>()
  for (const name of names) {
    if (NEVER_SWEEP.has(name)) continue
    const { fileKey, kind } = fileKeyAndKind(name)
    if (kind !== 'payload') continue
    try {
      const age = now - statSync(join(dir, name)).mtimeMs
      if (age <= STALE_AFTER_MS) freshPayloadKeys.add(fileKey)
    } catch {
      /* raced with something else removing it; irrelevant either way */
    }
  }

  for (const name of names) {
    if (NEVER_SWEEP.has(name)) continue
    const { fileKey, kind } = fileKeyAndKind(name)
    // An events file is appended on every turn and idle between them, so its
    // mtime says "last event" rather than "still alive" — protected while the
    // payload beside it is fresh, exactly like the settings and cmd files.
    if ((kind === 'settings' || kind === 'cmd' || kind === 'events') && freshPayloadKeys.has(fileKey)) continue
    try {
      const full = join(dir, name)
      const age = now - statSync(full).mtimeMs
      if (age > STALE_AFTER_MS) rmSync(full, { force: true })
    } catch {
      /* already gone, or a live process is touching it right now - either way, leave it */
    }
  }
}

/**
 * The context window for a session, in order of authority.
 *
 * 1. The statusLine payload. A direct statement, per model, correct from token
 *    zero, and the only one that still exists — claude 2.1.221 dropped
 *    "(1M context)" from its startup banner.
 * 2. The banner, for a CLI old enough to still print it.
 * 3. Null, and `contextLimitFor` falls back to inferring the tier from observed
 *    usage. That cannot be right below 200k, but it is never wrong in the
 *    dangerous direction.
 *
 * A named function rather than a lambda inside the ContextWatcher construction
 * because this ordering is the whole point of the statusLine channel, and a
 * lambda in a constructor call is the one shape no suite here can reach.
 *
 * `sessionId` is safe to use as the payload key here, though the two are not
 * the same thing in general. This is only ever called from the context
 * watcher, and there are exactly three kinds of session it watches:
 *
 *  - a local session Stoke minted an id for, whose statusLine key IS that id;
 *  - a remote session, which has no key and no payload at all — its `claude`
 *    runs on the far machine — so this falls through to the banner for it,
 *    exactly as it did before the payload existed;
 *  - and not a `--continue`, whose files are named after a launch key: it is
 *    never watched, because context.ts:99 no-ops on the empty id it has.
 *
 * So no caller can reach here holding a key that names somebody else's file.
 */
export function windowFor(sessionId: string, bannerWindow: number | null): number | null {
  return readStatusLine(sessionId)?.contextWindowSize ?? bannerWindow ?? null
}

/**
 * The user's own statusLine command, so it can be passed through when the
 * line is not suppressed. Read at launch rather than cached, because the file
 * is theirs and they can change it at any time.
 *
 * Read-only, always: Stoke never writes to Claude Code's own files.
 */
export function userStatusLineCommand(
  settingsFile: string = join(homedir(), '.claude', 'settings.json')
): string {
  try {
    // A leading BOM makes JSON.parse throw. PowerShell 5.1's
    // `Set-Content -Encoding utf8` writes one (CLAUDE.md gotcha 8), and a
    // user hitting that on their own ~/.claude/settings.json would otherwise
    // silently lose their status line here with no diagnostic. Stripped
    // before parsing, never written back — this function still only reads.
    const raw = JSON.parse(readFileSync(settingsFile, 'utf8').replace(/^﻿/, '')) as {
      statusLine?: { type?: string; command?: string }
    }
    const sl = raw?.statusLine
    if (!sl || sl.type !== 'command') return ''
    return typeof sl.command === 'string' ? sl.command.trim() : ''
  } catch {
    return ''
  }
}
